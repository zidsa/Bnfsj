import { buildSync } from "esbuild";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const source = resolve(
  process.argv[2] || fileURLToPath(new URL("..", import.meta.url)),
);
buildSync({
  entryPoints: [resolve(source, "src/product-entry.js")],
  outfile: resolve(source, "assets/bnfsj-product.js"),
  bundle: true,
  format: "iife",
  platform: "browser",
  target: ["es2020"],
  legalComments: "none",
  charset: "utf8",
  banner: {
    js: "/* Generated by scripts/build-runtime.mjs from src/product-entry.js. */",
  },
});
